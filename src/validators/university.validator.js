import { z } from 'zod';

const universityTypes = ['PUBLIC', 'PRIVATE', 'CHARTERED', 'FAITH_BASED', 'OTHER'];
const universityStatuses = ['ACTIVE', 'INACTIVE', 'SUSPENDED', 'CLOSED'];

export const createUniversitySchema = z.object({
    name: z.string().min(1, 'University name is required.').max(200),
    code: z.string().max(20).optional(),
    type: z.enum(universityTypes).optional(),
    established_date: z.string().optional(),
    accreditation_body: z.string().max(200).optional(),
    accreditation_status: z.string().max(100).optional(),
    accreditation_expiry: z.string().optional(),
    address: z.string().max(500).optional(),
    phone: z.string().max(50).optional(),
    email: z.string().email().optional().or(z.literal('')),
    website: z.string().url().optional().or(z.literal('')),
    timezone: z.string().max(50).optional(),
    locale: z.string().max(10).optional(),
    currency: z.string().max(3).optional(),
    logo_url: z.string().url().optional().or(z.literal('')),
    favicon_url: z.string().url().optional().or(z.literal('')),
    primary_color: z.string().max(7).optional(),
    secondary_color: z.string().max(7).optional(),
    contact_person_name: z.string().max(200).optional(),
    contact_person_email: z.string().email().optional().or(z.literal('')),
    contact_person_phone: z.string().max(50).optional(),
    mission_statement: z.string().max(2000).optional(),
    vision_statement: z.string().max(2000).optional(),
    motto: z.string().max(500).optional(),
    max_campuses: z.union([z.string(), z.number()]).optional(),
    max_students: z.union([z.string(), z.number()]).optional(),
    status: z.enum(universityStatuses).optional(),
});

