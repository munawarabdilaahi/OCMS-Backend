import { z } from 'zod';

const facultyStatuses = ['ACTIVE', 'INACTIVE', 'SUSPENDED', 'CLOSED'];

export const createFacultySchema = z.object({
    name: z.string().min(1, 'Faculty name is required.').max(200),
    code: z.string().max(20).optional(),
    established_date: z.string().optional(),
    description: z.string().max(1000).optional(),
    phone: z.string().max(50).optional(),
    email: z.string().email().optional().or(z.literal('')),
    website: z.string().url().optional().or(z.literal('')),
    dean_name: z.string().max(200).optional(),
    dean_email: z.string().email().optional().or(z.literal('')),
    dean_phone: z.string().max(50).optional(),
    office_location: z.string().max(200).optional(),
    office_hours: z.string().max(200).optional(),
    vision: z.string().max(2000).optional(),
    mission: z.string().max(2000).optional(),
    accreditation_body: z.string().max(200).optional(),
    accreditation_status: z.string().max(100).optional(),
    accreditation_expiry: z.string().optional(),
    max_departments: z.union([z.string(), z.number()]).optional(),
    student_capacity: z.union([z.string(), z.number()]).optional(),
    facilities: z.any().optional(),
    research_areas: z.any().optional(),
    campus_id: z.number().int().positive('Campus is required.'),
    status: z.enum(facultyStatuses).optional(),
});

