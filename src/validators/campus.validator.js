import { z } from 'zod';

const campusTypes = ['MAIN', 'BRANCH', 'VIRTUAL', 'SATELLITE', 'OTHER'];
const campusStatuses = ['ACTIVE', 'INACTIVE', 'SUSPENDED', 'CLOSED'];

export const createCampusSchema = z.object({
    name: z.string().min(1, 'Campus name is required.').max(200),
    code: z.string().max(20).optional(),
    type: z.enum(campusTypes).optional(),
    established_date: z.string().optional(),
    address: z.string().max(500).optional(),
    phone: z.string().max(50).optional(),
    email: z.string().email().optional().or(z.literal('')),
    website: z.string().url().optional().or(z.literal('')),
    timezone: z.string().max(50).optional(),
    locale: z.string().max(10).optional(),
    currency: z.string().max(3).optional(),
    campus_director: z.string().max(200).optional(),
    director_email: z.string().email().optional().or(z.literal('')),
    director_phone: z.string().max(50).optional(),
    max_capacity: z.union([z.string(), z.number()]).optional(),
    facilities: z.any().optional(),
    accreditation_body: z.string().max(200).optional(),
    accreditation_status: z.string().max(100).optional(),
    accreditation_expiry: z.string().optional(),
    operating_hours: z.string().max(200).optional(),
    emergency_contact: z.string().max(200).optional(),
    emergency_phone: z.string().max(50).optional(),
    campus_size: z.union([z.string(), z.number()]).optional(),
    buildings_count: z.union([z.string(), z.number()]).optional(),
    virtual_campus_url: z.string().url().optional().or(z.literal('')),
    parking_capacity: z.union([z.string(), z.number()]).optional(),
    transport_routes: z.any().optional(),
    library_hours: z.string().max(200).optional(),
    cafeteria_count: z.union([z.string(), z.number()]).optional(),
    sports_facilities: z.any().optional(),
    medical_facilities: z.string().max(500).optional(),
    security_details: z.string().max(500).optional(),
    university_id: z.number().int().positive('University is required.'),
    status: z.enum(campusStatuses).optional(),
});

